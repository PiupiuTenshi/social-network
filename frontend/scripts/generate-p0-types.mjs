#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';

const root = resolve(import.meta.dirname, '..', '..');
const source = resolve(root, 'docs/contracts/p0/openapi.json');
const output = resolve(root, 'frontend/src/app/core/api/p0-contract.types.ts');
const spec = JSON.parse(await readFile(source, 'utf8'));
const schemas = spec.components.schemas;

function propertyName(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function typeOf(schema) {
  if (!schema) return 'unknown';
  if (schema.$ref) return schema.$ref.split('/').at(-1);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  if (schema.type === 'array') return `ReadonlyArray<${typeOf(schema.items)}>`;
  if (schema.type === 'string') return 'string';
  if (schema.type === 'boolean') return 'boolean';
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  if (schema.type === 'object' || schema.properties) {
    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(
      ([name, value]) =>
        `readonly ${propertyName(name)}${required.has(name) ? '' : '?'}: ${typeOf(value)};`,
    );
    return `{ ${fields.join(' ')} }`;
  }
  return 'unknown';
}

const lines = [
  '/* This file is generated by frontend/scripts/generate-p0-types.mjs from docs/contracts/p0/openapi.json. */',
  '/* Do not hand-edit; update the locked P0 contract and regenerate. */',
  '',
];
for (const [name, schema] of Object.entries(schemas)) {
  if (schema.type === 'object' || schema.properties) {
    const required = new Set(schema.required ?? []);
    lines.push(`export interface ${name} {`);
    for (const [property, value] of Object.entries(schema.properties ?? {})) {
      lines.push(
        `  readonly ${propertyName(property)}${required.has(property) ? '' : '?'}: ${typeOf(value)};`,
      );
    }
    lines.push('}', '');
  } else {
    lines.push(`export type ${name} = ${typeOf(schema)};`, '');
  }
}
const prettierConfig = await resolveConfig(output);
const formatted = await format(`${lines.join('\n')}\n`, {
  ...prettierConfig,
  parser: 'typescript',
});
await writeFile(output, formatted, 'utf8');
console.log(`Generated ${Object.keys(schemas).length} P0 contract types: ${output}`);
